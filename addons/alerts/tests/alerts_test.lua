local oc = require("testkit.oc")
local t = require("testkit.test")
oc.install()

local event = require("event")
local addons = require("addons.core")
local outputs = {}
oc.addComponent("redstone", {setOutput = function (side, level) outputs[side] = level end})
local alerts = addons.load("alerts", {redstoneSide = "top", redstoneLevel = "warning"})
local logs = {}
event.listen("log_warning", function (_, text) logs[#logs + 1] = "W "..text end)
event.listen("log_error", function (_, text) logs[#logs + 1] = "E "..text end)
event.listen("log_info", function (_, text) logs[#logs + 1] = "I "..text end)
local base = oc.leftovers()

t.test("raise logs once, updates log again, redstone on", function ()
  t.truthy(alerts.raise("t3", "warning", "T3 needs attention"))
  t.falsy(alerts.raise("t3", "warning", "T3 needs attention"))
  t.equal(#logs, 1) t.equal(logs[1], "W [Alert] T3 needs attention")
  t.equal(outputs[1], 15)
  alerts.raise("power", "critical", "Power 5%")
  t.equal(logs[2], "E [Alert] Power 5%")
  t.equal(alerts.count(), 2) t.equal(alerts.worst(), "critical")
  t.equal(alerts.list()[1].key, "power")
end)

t.test("clear logs fixed, redstone off when none left", function ()
  t.truthy(alerts.clear("t3"))
  t.equal(logs[#logs], "I [Alert] Fixed: T3 needs attention")
  t.equal(outputs[1], 15)
  alerts.clear("power")
  t.equal(outputs[1], 0)
  t.falsy(alerts.clear("power"))
end)

t.test("alerts pushed as signals while started", function ()
  alerts.start()
  event.push("alert_raise", "me", "warning", "Disks 95% full")
  t.truthy(alerts.isActive("me"))
  event.push("alert_clear", "me")
  t.falsy(alerts.isActive("me"))
  alerts.stop()
  t.equal(oc.leftovers(), base)
end)

return t.finish()
