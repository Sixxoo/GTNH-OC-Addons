local oc = require("testkit.oc")
local t = require("testkit.test")
oc.install()

local event = require("event")
local filesystem = require("filesystem")
local addons = require("addons.core")
local path = os.tmpname()
filesystem.remove(path)
local history = addons.load("craft-history", {filePath = path, keep = 3})

local base = oc.leftovers()

t.test("jobs from cpu-monitor are recorded and written", function ()
  history.start()
  event.push("ae2_job_done", "Main", "Iron Ingot", 64, 30)
  event.push("ae2_job_done", "Main", "Gear", 4, 10)
  event.push("ae2_job_done", "Big", "Iron Ingot", 128, 50)
  local recent = history.recent(2)
  t.equal(#recent, 2) t.equal(recent[1].size, 128) t.equal(recent[2].label, "Gear")
  local stats = history.stats()
  t.equal(stats[1].label, "Iron Ingot") t.equal(stats[1].items, 192) t.equal(stats[1].jobs, 2)
  history.stop()
  t.equal(oc.leftovers(), base)
end)

t.test("only the newest are kept, the file reads back", function ()
  history.add({cpu = "Main", label = "Plate", size = 8, seconds = 5})
  t.equal(#history.recent(10), 3)
  history.clear()
  history.load()
  local recent = history.recent(10)
  t.equal(#recent, 3) t.equal(recent[1].label, "Plate") t.equal(recent[3].label, "Gear")
end)

filesystem.remove(path)
return t.finish()
