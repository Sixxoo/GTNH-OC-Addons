local oc = require("testkit.oc")
local t = require("testkit.test")
oc.install()

local filesystem = require("filesystem")
local addons = require("addons.core")
local path = os.tmpname()
filesystem.remove(path)
local stats = addons.load("stats", {filePath = path, keepHours = 24, saveSeconds = 300})
local base = oc.leftovers()

t.test("counters: total, last hours, per hour", function ()
  stats.start()
  stats.add("cycles") stats.add("cycles", 2)
  oc.advance(3600)
  stats.add("cycles")
  t.equal(stats.total("cycles"), 4)
  t.equal(stats.last("cycles", 1), 1)
  t.equal(stats.last("cycles", 24), 4)
  t.equal(math.floor(stats.rate("cycles", 24) + 0.5), 4)
  local hours = stats.hours("cycles", 3)
  t.equal(#hours, 3) t.equal(hours[3], 1) t.equal(hours[2], 3) t.equal(hours[1], 0)
end)

t.test("readings: last, min, max, average, per hour", function ()
  stats.record("water", 100) stats.record("water", 300)
  local r = stats.reading("water")
  t.equal(r.last, 300) t.equal(r.min, 100) t.equal(r.max, 300) t.equal(r.avg, 200)
  t.equal(stats.hours("water", 2)[1], nil) t.equal(stats.hours("water", 2)[2], 200)
  t.equal(stats.reading("nothing"), nil)
end)

t.test("saved on stop, read back with uptime; old hours dropped", function ()
  stats.stop()
  t.equal(oc.leftovers(), base)
  local up = stats.uptime().total
  t.equal(up, 3600)
  stats.setup({filePath = path, keepHours = 24, saveSeconds = 300})
  stats.load()
  t.equal(stats.total("cycles"), 4)
  t.equal(stats.reading("water").max, 300)
  t.equal(stats.uptime().total, 3600)
  stats.start()
  oc.advance(25 * 3600)
  stats.add("cycles")
  t.equal(stats.last("cycles", 48), 1)
  t.equal(stats.total("cycles"), 5)
  t.equal(stats.uptime().session, 25 * 3600)
  stats.stop()
end)

t.test("a broken file starts empty", function ()
  local file = io.open(path, "w") file:write("return {oops") file:close()
  stats.load()
  t.equal(stats.total("cycles"), 0)
end)

filesystem.remove(path)
return t.finish()
