local oc = require("testkit.oc")
local t = require("testkit.test")
oc.install()

local event = require("event")
local addons = require("addons.core")
local ui = addons.load("neon-ui")
local tabs = addons.load("tabs")
local base = oc.leftovers()

local bar = tabs.new({{id = "overview", title = "OVERVIEW"}, {id = "stats", title = "STATISTICS"}, {id = "log", title = "LOG"}})

t.test("select by id or number, wraps around", function ()
  t.equal(bar:current(), "overview")
  t.truthy(bar:select("log")) t.equal(bar:index(), 3)
  t.falsy(bar:select("log"))
  bar:next() t.equal(bar:current(), "overview")
  bar:prev() t.equal(bar:current(), "log")
  t.falsy(bar:select(9))
end)

t.test("keys: Tab, Shift+Tab, arrows, numbers", function ()
  local keys = require("keyboard").keys
  bar:select(1)
  t.truthy(bar:key(9, keys.tab)) t.equal(bar:index(), 2)
  oc.shift = true bar:key(9, keys.tab) oc.shift = false t.equal(bar:index(), 1)
  bar:key(0, keys.right) t.equal(bar:index(), 2)
  bar:key(0, keys.left) t.equal(bar:index(), 1)
  t.truthy(bar:key(string.byte("3"), 4)) t.equal(bar:current(), "log")
  t.falsy(bar:key(string.byte("q"), keys.q))
end)

t.test("draw and touch", function ()
  bar:select(1)
  local cv = ui.canvas(60, 3)
  bar:draw(cv, 14, 2)
  t.snapshot("tabs", cv:lines())
  t.equal(bar:width(), #" 1 OVERVIEW " + 1 + #" 2 STATISTICS " + 1 + #" 3 LOG ")
  t.truthy(bar:touch(14 + #" 1 OVERVIEW " + 1, 2)) t.equal(bar:current(), "stats")
  t.falsy(bar:touch(5, 2))
end)

t.test("listen: keys and touches change the tab, stop cleans up", function ()
  local changed
  bar:select(1)
  bar:listen(function (id) changed = id end)
  event.push("key_down", "kb", 0, require("keyboard").keys.right)
  t.equal(changed, "stats")
  event.push("touch", "screen", 14, 2)
  t.equal(changed, "overview")
  bar:stop()
  t.equal(oc.leftovers(), base)
end)

return t.finish()
