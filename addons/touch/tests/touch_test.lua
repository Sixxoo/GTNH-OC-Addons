local oc = require("testkit.oc")
local t = require("testkit.test")
oc.install()

local event = require("event")
local addons = require("addons.core")
local ui = addons.load("neon-ui")
local touch = addons.load("touch", {repeatSeconds = 0.3})
local base = oc.leftovers()

local panel = touch.new()
local cv = ui.canvas(40, 5)

t.test("buttons are drawn and hit", function ()
  local w = panel:button(cv, 2, 2, "START", "start")
  t.equal(w, 7)
  panel:button(cv, 2 + w + 1, 2, "STOP", "stop", {active = true})
  panel:button(cv, 20, 2, "OFF", "off", {disabled = true})
  t.snapshot("buttons", cv:lines())
  t.equal(panel:hit(3, 2), "start")
  t.equal(panel:hit(11, 2), "stop")
  t.equal(panel:hit(21, 2), nil)
  t.equal(panel:hit(3, 3), nil)
end)

t.test("a quick second touch is one press", function ()
  t.equal(panel:press(3, 2), "start")
  t.equal(panel:press(3, 2), nil)
  oc.advance(1)
  t.equal(panel:press(3, 2), "start")
end)

t.test("listen calls back, clear forgets the areas", function ()
  local pressed
  panel:listen(function (id) pressed = id end)
  oc.advance(1)
  event.push("touch", "screen", 11, 2, 0, "player")
  t.equal(pressed, "stop")
  panel:clear()
  t.equal(panel:hit(11, 2), nil)
  panel:stop()
  t.equal(oc.leftovers(), base)
end)

return t.finish()
